@interface MetadataForFrame()
	@property (readwrite, retain) FrameMetadataParser *parser;
	@property (readwrite) size_t arrayIndex;
@end

@implementation MetadataForFrame

-(id)initForParser:(FrameMetadataParser *)inParser arrayIndex:(size_t)inArrayIndex
{
	if (!(self = [super init]))
		return nil;
	
	self.parser = inParser;
	self.arrayIndex = inArrayIndex;
	
	return self;
}

+(id)metadataForFirstFrameAtImagePath:(NSString *)path
{
	FrameMetadataParser *parser = [FrameMetadataParser parserForImagePath:path];
	return [parser metadataForFrame:0];
}

-(void)dealloc
{
	self.parser = nil;
	[super dealloc];
}

-(id)valueForKeyPath:(NSString *)keyPath
{
	return [self.parser valueForKeyPath:keyPath arrayIndex:self.arrayIndex];
}

-(int)frameNumber
{
	return [self getOptionalIntForKey:@"frame.frame_number" defaultVal:0];
}

-(double)universalComputerTimestamp
{
	/*  We go through a bit of a faff to determine a timestamp, since I have done various things in previous versions of code.
	 I used to just record time_received. Then I realised that for QI cameras I could record the time exposure finished.
	 I initially called that time_received3, then changed it to a more helpful name.   */
	NSNumber *timestamp = [self valueForKeyPath:@"frame.time_exposed"];
	if (timestamp == nil)
	{
		timestamp = [self valueForKeyPath:@"frame.time_received3"];	// I used this for a brief while before remaining it to time_exposed
		if (timestamp == nil)
			timestamp = [self valueForKeyPath:@"frame.time_received"];
	}
	
	if (timestamp != nil)
	{
		// We use timebase_start_uptime to correct the value and get a universally consistent timestamp
		// I leave it optional just to cope with synthetic plists where I probably didn't bother to define timebase_start_uptime
		return timestamp.doubleValue + [self getOptionalDoubleForKey:@"camera.timebase_start_uptime" defaultVal:0];
	}
	else
		return 0.0;
}

-(NSPoint)driftOffset
{
	NSString *offset = [self getOptionalStringForKey:@"frame.drift_offset" defaultVal:nil];
	NSPoint result;
	if (offset == nil)
	{
		// Back-compatibility with old plist format
		result = NSMakePoint(((NSNumber*)[self valueForKeyPath:@"sync_settings.drift_offset_x"]).floatValue,
							 ((NSNumber*)[self valueForKeyPath:@"sync_settings.drift_offset_y"]).floatValue);
	}
	else
		result = NSPointFromString(offset);
	return result;
}

-(NSBitmapImageRep *)frameBitmap
{
	return [self.parser frameBitmapForArrayIndex:self.arrayIndex];
}

-(NSString *)imageFileFullPath { return self.parser.imagePath; }
-(NSString *)frameDescNoPath
